// Lookup by Chinese name — the identifier the rest of the app uses
export const CARD_BY_ZH: Record<string, TarotCard> = Object.fromEntries(
  TAROT_CARDS.map((c) => [c.name.zh, c]),
);

/** Pre-written meaning for a card in its drawn orientation; null if unknown. */
export function getCardMeaning(zhName: string, reversed: boolean, locale: Locale): string | null {
  const card = CARD_BY_ZH[zhName];
  if (!card) return null;
  return (reversed ? card.rev : card.up)[locale];
}
